// Export routing — the same stationOf router as concept commands, applied to every src/0 export name.
export function dissolveExportsAtPiTrainStations(
  matrix: MindMatrix = buildMatrix(),
  exportNames: readonly string[] = ZERO_EXPORT_CATALOG,
) {
  const math = digitFolderMath(matrix)
  const base = dissolveAtPiTrainStations(matrix)
  const stationOf = base.stationOf
  const routed = exportNames.map((name) => {
    const station = stationOf(name)
    const entry = math.lookup[station]!
    return {
      export: name,
      station,
      order: entry.order,
      path: stationPathFromSequence(entry),
      folder: entry.folder,
      fusion: entry.fusion,
    }
  })
  const byStation = math.digits.map((entry) => ({
    digit: entry.digit,
    path: stationPathFromSequence(entry),
    folder: entry.folder,
    exports: routed.filter((row) => row.station === entry.digit).map((row) => row.export),
  }))
  const orphans = routed.filter((row) => !math.lookup[row.station]).length
  const stationsUsed = new Set(routed.map((row) => row.station)).size
  return {
    dissolved: orphans === 0 && exportNames.length > 0 && stationsUsed === 10,
    sequence: base.sequence,
    exportCount: exportNames.length,
    routed,
    byStation,
    stationOf,
    orphans,
    stationsUsed,
    root: merge(math.root, merkleFold(routed.map((row) => toUuid(`export-dissolve:${row.export}->${row.station}`)))),
    statement:
      'Dissolve src/0 exports at pi-train stations: each export routes to path src/d/r (sequence-derived, single-digit segments) by stationOf. Void overflow maps to src/0.',
    boundary:
      'Migration manifest over ZERO_EXPORT_CATALOG. Nested station paths are legal when steps come from the sequence; definitions still in src/0 until cut waves.',
  }
}

