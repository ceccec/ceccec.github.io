function logicRelRelativeImport(fromLogicRel: string, toLogicRel: string): string {
  const stripSrc = (p: string) => p.replace(/^src\//, '').replace(/\/index\.ts$/, '')
  const fromParts = stripSrc(fromLogicRel).split('/').filter(Boolean)
  const toParts = stripSrc(toLogicRel).split('/').filter(Boolean)
  let shared = 0
  while (shared < fromParts.length && shared < toParts.length && fromParts[shared] === toParts[shared]) shared++
  const ups = fromParts.length - shared
  const down = toParts.slice(shared).join('/')
  const prefix = ups > 0 ? `${'../'.repeat(ups)}` : './'
  return down ? `${prefix}${down}` : prefix.replace(/\/$/, '') || '.'
}

